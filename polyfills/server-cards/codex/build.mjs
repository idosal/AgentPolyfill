// Builds the Codex plugin's one file, plugin/dist/server.mjs, from src/ and the
// shared modules it imports from ../claude-code/mod/hooks (bundled, never
// copied). The ARD plugin (polyfills/ard/codex) builds the same way, through
// `bundle` and `bundleTests` below.
//
//   node build.mjs             build plugin/dist/server.mjs
//   node build.mjs --check     fail if plugin/dist/server.mjs is not what the sources build
//   node build.mjs --out DIR   build server.mjs into DIR instead (test/bundle.test.ts)
//   node build.mjs --tests     build the tests into test/.build, run by `npm test`
//
// The tests run against the committed file: every import of a shared module,
// from the Claude Code form's own rule tests too, is pointed at
// plugin/dist/server.mjs, and `--tests` does not rebuild it. Run `npm run build`
// after changing the sources; test/bundle.test.ts fails while it is stale.

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

const BANNER = (name, version, host = 'Codex') =>
  `// ${name} ${version}, for ${host}. Built from https://github.com/idosal/AgentPolyfill (Apache-2.0).\n` +
  '// Generated by build.mjs from the TypeScript sources; do not edit.'

/** The plugin's bundle, as text. */
export async function bundle({ esbuild, root, entry, name, version, host }) {
  const out = await esbuild.build({
    entryPoints: [resolve(root, entry)],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    legalComments: 'none',
    banner: { js: BANNER(name, version, host) },
    // Paths in the bundle's comments, relative to the repository: the same on every machine.
    absWorkingDir: resolve(here, '../../..'),
    logLevel: 'error',
  })
  return out.outputFiles[0].text
}

/**
 * The tests, each bundled to test/.build/<name>.test.mjs. `claude-code/testing`
 * is node:test with a small expect; a shared module (`hooks/<x>` in a Claude
 * Code test) and the adapter (`../src/...`) are the built plugin file.
 */
export async function bundleTests({ esbuild, root, files, server }) {
  const outDir = resolve(root, 'test/.build')
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })
  const shim = resolve(here, 'test/testing.ts')
  const toServer = relative(outDir, server).split('\\').join('/')
  const redirect = {
    name: 'to-the-bundle',
    setup(b) {
      b.onResolve({ filter: /^claude-code\/testing$/ }, () => ({ path: shim }))
      b.onResolve({ filter: /(^|\/)(hooks|src|dist)\/[\w.-]+$/ }, args => {
        const target = resolve(args.resolveDir, args.path)
        const shared = /[/\\]mod[/\\]hooks[/\\]/.test(target) && !target.endsWith('fixtures')
        // A host's adapter: this Codex form's, or another host's form built with these functions
        // (polyfills/server-cards/copilot), whose own src and bundle are the plugin file too.
        const adapter = /[/\\](codex|copilot)[/\\](src|plugin[/\\]dist)[/\\]/.test(target)
        return shared || adapter ? { path: `./${toServer}`, external: true } : undefined
      })
    },
  }
  for (const file of files) {
    await esbuild.build({
      entryPoints: [file],
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node20',
      outfile: join(outDir, basename(file).replace(/\.test\.tsx?$/, '.test.mjs')),
      plugins: [redirect],
      logLevel: 'error',
    })
  }
}

export async function main({ esbuild, root, entry, name, version, ruleTests, host }) {
  const server = resolve(root, 'plugin/dist/server.mjs')
  const args = process.argv.slice(2)
  if (args.includes('--tests')) {
    const own = readdirSync(resolve(root, 'test'))
      .filter(f => f.endsWith('.test.ts'))
      .map(f => resolve(root, 'test', f))
    await bundleTests({ esbuild, root, files: [...ruleTests.map(f => resolve(root, f)), ...own], server })
    return
  }
  const text = await bundle({ esbuild, root, entry, name, version, host })
  const out = args.indexOf('--out')
  if (out >= 0) {
    const dir = resolve(args[out + 1] ?? '.')
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'server.mjs'), text)
    return
  }
  if (args.includes('--check')) {
    let held = ''
    try {
      held = readFileSync(server, 'utf8')
    } catch {}
    if (held !== text) {
      console.error(`${relative(process.cwd(), server)} is not what the sources build. Run: npm run build`)
      process.exit(1)
    }
    console.log(`${relative(process.cwd(), server)} is up to date`)
    return
  }
  mkdirSync(dirname(server), { recursive: true })
  writeFileSync(server, text)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const esbuild = await import('esbuild')
  await main({
    esbuild,
    root: here,
    entry: 'src/main.ts',
    name: 'mcp-server-cards',
    version: JSON.parse(readFileSync(join(here, 'plugin/.codex-plugin/plugin.json'), 'utf8')).version,
    // The Claude Code form's rule tests, run here against the bundle.
    ruleTests: ['card', 'configure', 'discover', 'format', 'offer'].map(n => `../claude-code/mod/tests/${n}.test.ts`),
  })
}
