// Builds the Antigravity plugin's one file, plugin/dist/server.mjs, from src/
// and the shared modules it imports (../claude-code/mod/hooks, ../codex/src),
// bundled, never copied. The ARD plugin (polyfills/ard/antigravity) builds
// the same way, through `build` below.
//
//   node build.mjs             build plugin/dist/server.mjs
//   node build.mjs --check     fail if plugin/dist/server.mjs is not what the sources build
//   node build.mjs --out DIR   build server.mjs into DIR instead (test/bundle.test.ts)
//   node build.mjs --tests     build the tests into test/.build, run by `npm test`

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

const BANNER = (name, version) =>
  `// ${name} ${version}, for Antigravity. Built from https://github.com/idosal/AgentPolyfill (Apache-2.0).\n` +
  '// Generated by build.mjs from the TypeScript sources; do not edit.'

const common = { bundle: true, format: 'esm', platform: 'node', target: 'node20', legalComments: 'none', logLevel: 'error' }

// `claude-code/testing` (the shared rule tests' kit) is node:test with a small expect.
const testingKit = {
  name: 'testing-kit',
  setup(b) {
    b.onResolve({ filter: /^claude-code\/testing$/ }, () => ({ path: resolve(here, '../codex/test/testing.ts') }))
  },
}

/**
 * `ruleTests`: shared rule tests (paths relative to `root`), built from the
 * same sources the bundle is, with the host left at its defaults, as the
 * Codex form runs them.
 */
export async function build({ esbuild, root, entry = 'src/main.ts', name, version, ruleTests = [] }) {
  const server = resolve(root, 'plugin/dist/server.mjs')
  const args = process.argv.slice(2)
  if (args.includes('--tests')) {
    const outDir = resolve(root, 'test/.build')
    rmSync(outDir, { recursive: true, force: true })
    mkdirSync(outDir, { recursive: true })
    const own = readdirSync(resolve(root, 'test')).filter(f => f.endsWith('.test.ts')).map(f => resolve(root, 'test', f))
    for (const f of [...ruleTests.map(t => resolve(root, t)), ...own])
      await esbuild.build({ ...common, entryPoints: [f], outfile: join(outDir, basename(f).replace(/\.tsx?$/, '.mjs')), plugins: [testingKit] })
    return
  }
  const out = await esbuild.build({
    ...common,
    entryPoints: [resolve(root, entry)],
    write: false,
    banner: { js: BANNER(name, version) },
    // Paths in the bundle's comments, relative to the repository: the same on every machine.
    absWorkingDir: resolve(here, '../../..'),
  })
  const text = out.outputFiles[0].text
  const o = args.indexOf('--out')
  if (o >= 0) {
    const dir = resolve(args[o + 1] ?? '.')
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'server.mjs'), text)
    return
  }
  if (args.includes('--check')) {
    let held = ''
    try {
      held = readFileSync(server, 'utf8')
    } catch {}
    if (held !== text) {
      console.error(`${relative(process.cwd(), server)} is not what the sources build. Run: npm run build`)
      process.exit(1)
    }
    console.log(`${relative(process.cwd(), server)} is up to date`)
    return
  }
  mkdirSync(dirname(server), { recursive: true })
  writeFileSync(server, text)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const esbuild = await import('esbuild')
  await build({
    esbuild,
    root: here,
    name: 'mcp-server-cards',
    version: JSON.parse(readFileSync(join(here, 'plugin/plugin.json'), 'utf8')).version,
    // The shared discovery, validation, input and transport rules (the Claude Code form's tests).
    ruleTests: ['card', 'configure', 'discover', 'format', 'offer'].map(n => `../claude-code/mod/tests/${n}.test.ts`),
  })
}
