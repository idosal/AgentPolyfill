// Builds the one file the skill runs, skills/server-card-connector/scripts/card-to-connector.mjs,
// from src/ and the shared Server Cards modules it imports (bundled, never copied).
//
//   node build.mjs           build it
//   node build.mjs --check   fail if the committed file is not what the sources build

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, 'skills/server-card-connector/scripts/card-to-connector.mjs')
const { version } = JSON.parse(readFileSync(resolve(here, 'package.json'), 'utf8'))

const built = await esbuild.build({
  entryPoints: [resolve(here, 'src/cli.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  legalComments: 'none',
  banner: { js: `// card-to-connector ${version}, for Grok Bot. Built from https://github.com/idosal/AgentPolyfill (Apache-2.0).\n// Generated by build.mjs from the TypeScript sources; do not edit.` },
  absWorkingDir: resolve(here, '../../..'),
  logLevel: 'error',
})
const text = built.outputFiles[0].text
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf8')
  } catch {}
  if (current !== text) {
    console.error(`${out} is not what the sources build: run \`npm run build\`.`)
    process.exit(1)
  }
} else {
  writeFileSync(out, text)
  console.log(`built ${out} (${text.length} bytes)`)
}
