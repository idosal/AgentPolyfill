// Shared modules are bundled, never copied. Tests import the committed bundle.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export async function main({ esbuild, root, ruleTests }) {
  const args = process.argv.slice(2)
  if (args.includes('--tests')) {
    const out = join(root, 'test/.build')
    rmSync(out, { recursive: true, force: true })
    mkdirSync(out, { recursive: true })
    const files = [...ruleTests.map(p => resolve(root, p)), ...readdirSync(join(root, 'test')).filter(p => p.endsWith('.test.ts')).map(p => join(root, 'test', p))]
    for (const file of files) {
      await esbuild.build({
        entryPoints: [file], bundle: true, format: 'esm', platform: 'node', target: 'node22',
        outfile: join(out, basename(file).replace('.test.ts', '.test.mjs')),
        plugins: [{ name: 'test-installed-bundle', setup(build) {
          build.onResolve({ filter: /^claude-code\/testing$/ }, () => ({ path: resolve(here, '../codex/test/testing.ts') }))
          build.onResolve({ filter: /pi-rpc(?:\.ts)?$/ }, a => ({ path: '../pi-rpc.ts', external: true }))
          build.onResolve({ filter: /(^|\/)(hooks|src)\/[\w.-]+$/ }, a => {
            const target = resolve(a.resolveDir, a.path)
            if ((/\/mod\/hooks\//.test(target) && !target.endsWith('fixtures')) || /\/(pi|codex)\/src\//.test(target))
              return { path: '../../extension/dist/index.js', external: true }
          })
        }}],
        logLevel: 'error',
      })
    }
    return
  }
  const { name, version } = JSON.parse(readFileSync(join(root, 'extension/package.json'), 'utf8'))
  const result = await esbuild.build({
    absWorkingDir: resolve(here, '../../..'), entryPoints: [join(root, 'src/index.ts')],
    bundle: true, write: false, format: 'esm', platform: 'node', target: 'node22',
    external: ['@earendil-works/*'], legalComments: 'none',
    banner: { js: `// ${name} ${version}, for Pi. Generated by build.mjs; do not edit.\n// https://github.com/idosal/AgentPolyfill (Apache-2.0).` }, logLevel: 'error',
  })
  const outAt = args.indexOf('--out')
  const out = outAt >= 0 ? resolve(args[outAt + 1]) : join(root, 'extension/dist')
  mkdirSync(out, { recursive: true })
  writeFileSync(join(out, 'index.js'), result.outputFiles[0].text)
  console.log(`${relative(root, join(out, 'index.js'))} built`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main({ esbuild: await import('esbuild'), root: here,
    ruleTests: ['card', 'configure', 'discover', 'format', 'offer'].map(n => `../claude-code/mod/tests/${n}.test.ts`) })
}
