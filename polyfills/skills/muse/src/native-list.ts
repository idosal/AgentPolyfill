import { randomUUID } from 'node:crypto';
import { lstatSync, mkdirSync, readFileSync, readdirSync, renameSync, rmdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { museConfigDir } from '../../../events/muse/src/muse-config.ts';
import { nativeFolder, inlineReferences } from './routes.ts';
import { join } from 'node:path';
import { labelDir, MAX_STUBS, plain, stubNames } from '../../codex/src/stubs.ts';
import type { Listed } from '../../core/src/skills.ts';

const prefix = 'mcp-skill-reference--';
const owned = /^mcp-skill-reference--([a-z0-9_.:@-]{1,64}-[a-f0-9]{6})--[a-f0-9]{16}$/;
const marker = '<!-- Generated by AgentPolyfill mcp-skill-reference -->';

export function nativeRoot(env = process.env) {
    return join(museConfigDir(env), 'skills');
}
/** Only the publisher's listing is used here. Skill contents stay out of Muse's skill folder. */
export function syncNativeList(root: string, listed: Listed[], keep: Set<string>) {
    mkdirSync(root, { recursive: true });
    if (!lstatSync(root).isDirectory()) throw Error('Muse skills root must be a directory.');
    const lock = join(root, '.' + prefix + 'lock');
    try { mkdirSync(lock); } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
        // A crashed helper may have left this short-lived, synchronous writer's lock.
        if (Date.now() - lstatSync(lock).mtimeMs < 30000) return;
        try { rmdirSync(lock); mkdirSync(lock); } catch { return; }
    }
    try {
        const shown = listed.filter(item => !item.declined && item.entry.resources !== 'dynamic').slice(0, MAX_STUBS);
        const names = stubNames(shown);
        const wanted = new Set<string>();
        for (const item of shown) {
            const { label, entry } = item;
            const name = nativeFolder(item);
            wanted.add(name);
            const dir = join(root, name);
            const file = join(dir, 'SKILL.md');
            mkdirSync(dir, { recursive: true });
            if (!lstatSync(dir).isDirectory()) continue;
            const description = '[MCP publisher ' + label + '] ' + plain(entry.frontmatter.description, 900);
            const body = ['---', 'name: ' + JSON.stringify(names.get(item)), 'description: ' + JSON.stringify(description), '---', '', marker,
                'Published name: ' + plain(entry.frontmatter.name, 100), 'Publisher URI: ' + JSON.stringify(entry.uri),
                'Use the native activation receipt to read the publisher files. For a how-to question choose the relevant listed reference in the same request. If the reader is unavailable or the person declines, the publisher guide has not been read.',
                'Choose one reference number for this question, or 0 for the main guide alone.',
                ...inlineReferences(entry).map((path,index) => 'Reference '+(index+1)+': '+path),
                'Use files already present in this conversation for follow-up questions. Say which requested details the source does not cover.', ''].join('\n');
            const stat = lstatSync(file, { throwIfNoEntry: false });
            if (stat) {
                if (!stat.isFile()) continue;
                const old = readFileSync(file, 'utf8');
                if (old === body || !old.includes('\n' + marker + '\n')) continue;
            }
            const tmp = join(dir, '.skill-' + randomUUID());
            try {
                writeFileSync(tmp, body, { flag: 'wx', mode: 0o600 });
                renameSync(tmp, file);
            } finally {
                if (lstatSync(tmp, { throwIfNoEntry: false })) unlinkSync(tmp);
            }
        }
        const preserve = new Set([...keep].map(labelDir));
        for (const item of readdirSync(root, { withFileTypes: true })) {
            const match = owned.exec(item.name);
            if (!match || !item.isDirectory() || wanted.has(item.name) || preserve.has(match[1]!)) continue;
            const dir = join(root, item.name);
            const file = join(dir, 'SKILL.md');
            if (!lstatSync(file, { throwIfNoEntry: false })?.isFile() || !readFileSync(file, 'utf8').includes('\n' + marker + '\n')) continue;
            unlinkSync(file);
            if (!readdirSync(dir).length) rmdirSync(dir);
        }
    } finally { rmdirSync(lock); }
}
